/**
 * The briefing (system prompt) for the model (docs/01-filozofie.md, ch. 9.2).
 * In English, which costs fewer tokens; the model answers in the user's
 * language. What the program knows about its own language (functions, error
 * codes) comes from the program, so the briefing never goes stale.
 */

import type { AiSheetContext } from './contract.js';
import { selectTheory } from './theorySearch.js';

/** One turn of a conversation, as the user and the model wrote it. */
export interface ChatTurn {
  readonly role: 'user' | 'assistant';
  readonly text: string;
  /** ISO time it was written. */
  readonly time?: string;
  /** For an answer: the model that wrote it. */
  readonly model?: string;
  /** For an answer: the sources it cited, with their state when it was written. */
  readonly citations?: readonly { readonly id: string; readonly status: 'ok' | 'unknown' | 'misquoted'; readonly quote?: string }[];
  /** For an answer: the theory sections the model was given, and how many the theory has. */
  readonly theory?: { readonly sent: readonly string[]; readonly total: number };
}

export interface BriefingInput {
  /** The user's language as a BCP 47 tag ("cs"); the model answers in it. */
  readonly language: string;
  readonly sheet: AiSheetContext;
  /** Overview of the calculation language, generated by the program. */
  readonly languageGuide?: string;
  /** Company rules for the model (AiPolicy.instructions); they come last and win. */
  readonly companyInstructions?: string;
  /** What the user asks: from larger theory, the sections for it are chosen. */
  readonly query?: string;
  /** Section ids already cited in the conversation; they go along. */
  readonly cited?: readonly string[];
  /** The sheet's memory from earlier conversations (ch. 9.7). */
  readonly memory?: string;
}

/** The briefing, and which theory sections it carries. */
export interface PreparedBriefing {
  readonly text: string;
  readonly theory?: { readonly sent: readonly string[]; readonly total: number; readonly whole: boolean };
}

/** English name of a language, for "answer in Czech". */
export function languageName(tag: string): string {
  try {
    return new Intl.DisplayNames(['en'], { type: 'language' }).of(tag) ?? tag;
  } catch {
    return tag;
  }
}

/** Three backticks: written inside the briefing's own template strings. */
const FENCE = '`'.repeat(3);

/** Theory longer than this goes in part (searching it comes later, ch. 9.6). */
const MAX_THEORY_CHARS = 40_000;

/** The theory as the model reads it: "[T3] Title" over each section. */
export function theoryText(theory: NonNullable<AiSheetContext['theory']>): string {
  let used = 0;
  const parts: string[] = [];
  for (const s of theory) {
    const part = `${s.id ? `[${s.id}] ` : ''}${s.title}\n${s.text}`.trim();
    if (used + part.length > MAX_THEORY_CHARS) {
      parts.push(`(${theory.length - parts.length} more sections not shown)`);
      break;
    }
    parts.push(part);
    used += part.length;
  }
  return parts.join('\n\n');
}

/** Numbered lines, so the model can point at them. */
export function numbered(source: string): string {
  return source
    .split(/\r?\n/)
    .map((line, i) => `${String(i + 1).padStart(3)} | ${line}`)
    .join('\n');
}

export function briefing(input: BriefingInput): string {
  return prepareBriefing(input).text;
}

export function prepareBriefing(input: BriefingInput): PreparedBriefing {
  const { sheet } = input;
  const selection = sheet.theory && sheet.theory.length > 0 ? selectTheory(sheet.theory, input.query ?? '', input.cited ?? []) : undefined;
  const contents =
    selection && !selection.whole
      ? `The theory has ${selection.total} sections; those that match the question are given in full below, the others only by title here. If the question needs one of the others, say which, so the user can ask about it.
${sheet.theory!.filter((s) => s.id).map((s) => `[${s.id}] ${s.title}`).join('\n')}

`
      : '';
  const parts = [
    `You are the assistant inside Kalketa, a program for engineering calculations. A calculation is a sheet: lines of a small calculation language with units, evaluated by the program's own core and printed like a hand calculation.`,
    `Rules:
- You never change the calculation yourself. You explain, check and propose; a person decides. Write a proposed change of the calculation as a block that names the lines it replaces, with the new lines only (no line numbers inside); the program shows it with Accept and Reject:
  ${FENCE}change 8
  profil := pick(Profily_IPE, "IPE 220")
  ${FENCE}
  "change 12-14" replaces lines 12 to 14 (an empty block deletes them), "change after 14" inserts new lines after line 14. Propose only lines in the calculation language, one block per place.
- Never invent data. Values of materials, profiles or loads come from tables in the sheet or from a source the user can check; if one is missing, say so and propose where it could come from.
- State every assumption (coefficients, categories) openly.
- Point at lines by their numbers. The program computes; do not recalculate results by hand unless asked.
- Answer in ${languageName(input.language)}, briefly and to the point. Keep identifiers, units and formulas as they are written in the sheet.
- Lines of the sheet are given with their numbers; the findings and computed results refer to those numbers.`,
    input.languageGuide ? `Calculation language:\n${input.languageGuide}` : '',
    `The sheet "${sheet.title}" (read-only for you):\n${numbered(sheet.source)}`,
    sheet.findings && sheet.findings.length > 0 ? `Findings of the program (errors, warnings, checks):\n${sheet.findings.join('\n')}` : 'The program found no errors and no failed checks.',
    sheet.theory && sheet.theory.length > 0
      ? `Theory and references the author chose for this calculation (in the sheet's language). Answer from them:
- Cite the section you use by its id as given, like [T3] (the sheet's own sources) or [PP:T3] (a theory library). When you rely on its exact words, quote them verbatim in quotation marks right before the citation: "…" [T3]. The program checks every citation and marks the ones it cannot find as unsupported.
- Cite only sections given here in full, and use their terms. If they do not cover the question, say so, then answer from general knowledge without a citation.

${sheet.libraries && sheet.libraries.length > 0 ? `Theory libraries: ${sheet.libraries.map((l) => `[${l.key}] ${l.title} (source: ${l.source})`).join('; ')}.\n\n` : ''}${contents}${selection!.sections.length > 0 ? theoryText(selection!.sections) : '(No section matches the question.)'}`
      : '',
    input.memory?.trim()
      ? `Memory of this sheet from earlier conversations (kept by you; where it disagrees with the sheet above, the sheet is right):\n${input.memory.trim()}`
      : '',
    input.companyInstructions ? `Company rules (they take precedence):\n${input.companyInstructions}` : '',
  ];
  return {
    text: parts.filter((p) => p !== '').join('\n\n'),
    ...(selection ? { theory: { sent: selection.sections.flatMap((s) => (s.id ? [s.id] : [])), total: selection.total, whole: selection.whole } } : {}),
  };
}

/**
 * The last question of a conversation that ends: the model rewrites the
 * sheet's memory (ch. 9.7) from the old one and what the conversation added.
 */
export function memoryInstruction(previous: string): string {
  return [
    'The conversation ends here. Rewrite the memory of this sheet for future conversations, so the next one does not start from nothing.',
    'In English, at most 150 words, short lines under these headings: Intent; Agreed assumptions; Checked (with the results); Open questions; Sources relied on (their ids, e.g. T3, PP:T3).',
    'Agreed assumptions are only what the user confirmed in the conversation or what the sheet itself states; anything you inferred yourself goes under Open questions.',
    'Plain text with those headings, not wrapped in a code block.',
    'Merge the previous memory with what this conversation added; leave out what no longer holds for the sheet as it is now, and do not repeat what the sheet itself says.',
    'Reply with the memory only.',
    previous.trim() ? `Previous memory:\n${previous.trim()}` : 'There is no previous memory.',
  ].join('\n');
}

/** A memory as the model wrote it, without a code block wrapped around it ("```" … "```"). */
export function cleanMemory(text: string): string {
  const trimmed = text.trim();
  const fenced = /^```[\w-]*\s*\n([\s\S]*?)\n?```$/.exec(trimmed);
  return (fenced ? fenced[1]! : trimmed).trim();
}
